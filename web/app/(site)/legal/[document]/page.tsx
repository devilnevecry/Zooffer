type PageProps = { params: Promise<{ document: string }> };

export function generateStaticParams() {
  return Object.keys(documents).map((document) => ({ document }));
}

export async function generateMetadata({ params }: PageProps): Promise<Metadata> {
  const { document: slug } = await params;
  const document = documents[slug];
  if (!document) return { title: "Документ не найден" };
  return {
    title: document.title,
    description: document.intro,
    alternates: { canonical: `/legal/${slug}` },
  };
}

export default async function LegalPage({ params }: PageProps) {
  const { document: slug } = await params;
  const document = documents[slug];
  if (!document) notFound();

  return (
    <div className="page">
      <div className="container legal-layout">
        <aside className="legal-nav">
          <span className="eyebrow">Документы</span>
          <nav aria-label="Юридические документы">
            {Object.entries(documents).map(([key, item]) => (
              <Link
                key={key}
                href={`/legal/${key}`}
                aria-current={key === slug ? "page" : undefined}
              >
                {item.title}
              </Link>
            ))}
          </nav>
          <div className="privacy-note">
            Версия от {new Date(document.updated).toLocaleDateString("ru-RU")}. Вопросы — через{" "}
            <Link href="/support">поддержку</Link>.
          </div>
        </aside>
        <article className="legal-document">
          <span className="eyebrow">Zooffer</span>
          <h1>{document.title}</h1>
          <p className="lead">{document.intro}</p>
          <p className="legal-meta">
            Редакция от {new Date(document.updated).toLocaleDateString("ru-RU")}
          </p>
          {document.sections.map((section) => (
            <section key={section.heading}>
              <h2>{section.heading}</h2>
              {section.paragraphs.map((paragraph) => (
                <p key={paragraph}>{paragraph}</p>
              ))}
              {section.bullets && (
                <ul>
                  {section.bullets.map((bullet) => (
                    <li key={bullet}>{bullet}</li>
                  ))}
                </ul>
              )}
            </section>
          ))}
          <div className="notice warn">
            Шаблон перед публикацией: замените поля в угловых скобках (&lt;ФИО&gt;, &lt;ИНН&gt;,
            &lt;АДРЕС&gt;, &lt;EMAIL&gt;) на реальные данные самозанятого и при необходимости
            согласуйте текст с юристом.
          </div>
        </article>
      </div>
    </div>
  );
}
